// ============================================================
// ボイスリーディング: コードを、前に鳴らしたコードから一番近い高さで鳴らす
//
//   度数の離れたコード（Ⅰ と Ⅶ など）が続くと、コードの高さが急に上がったり下がったりして不自然になる。
//   そこで、コードを「1オクターブ上げる・そのまま・1オクターブ下げる」の3つの高さから、
//   前のコードのルート（一番低い音）に一番近いものを選ぶ。
//
//   ・本来の高さ（ルートが C3〜B3 の範囲）から、上下1オクターブより遠くには行かない。
//     （前のコードがすでに高くなっていても、本来の高さの +12 までで止まる）
//   ・同じ近さなら、本来の高さを選ぶ（高さが少しずつずれていくのを防ぐ）。
//   ・ただし、強進行（ルートが完全4度上 = 完全5度下に進む和音。Ⅴ→Ⅰ・Ⅱm→Ⅴ など）は、完全5度「下」へ動かす
//     （上へ4度跳ぶと、終止した感じにならない。2026-11-24）。下に行きすぎるときだけ、いちばん近い高さ。
//
//   例（Key=C、本来のルート: Ⅰ=C3(48) Ⅵ=A3(57)）
//     前が Ⅵ(A3=57) → Ⅰ: 本来の C3(48) は 9半音下、C4(60) は 3半音上 → C4 を選ぶ（短3度上へ）
//     前が Ⅵ(A4=69) → Ⅰ: C5(72) は 本来の2オクターブ上になるので選べない。
//                         候補は C2(36) / C3(48) / C4(60) → C4(60) を選ぶ（6度下へ）
//
//   Arduino に依存しない（パソコンの上でもテストできる）。
// ============================================================

// 本来のルート（MIDIノート）から動かす量（-12 / 0 / +12 半音）を返す。
//   nominalRoot  : 本来の高さのルート（例: 48）
//   previousRoot : 前に鳴らしたコードの、実際のルート。まだ鳴らしていなければ -1
//   enabled      : false のときは、いつも 0（本来の高さ）
int chooseOctaveShift(int nominalRoot, int previousRoot, bool enabled);
