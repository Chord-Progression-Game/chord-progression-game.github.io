#include "chords.h"

// ============================================================
// ボイスリーディング: コードの高さ（ルート）を、ループ全体を見て決める
//
//   度数の離れたコード（Ⅰ と Ⅶ など）が続くと、コードの高さが急に上がったり下がったりして不自然になる。
//   そこで、各コードを「本来の高さ（ルートが baseC〜baseC+11）」「1オクターブ上」「1オクターブ下」の
//   3つの高さから選ぶ。選び方は2通り。
//
//   ① 計画（planOctaves / planBoardShifts。2026-11-24。ご指定）: ループ全体を見て、全部のコードの高さを、まとめて決める。
//      ・最初のコードは、いつも本来の高さ。そこから、全体の費用がいちばん小さい組み合わせを、動的計画法で選ぶ
//      ・費用: つながりの跳躍が小さいほどよい / 強進行（ルートが完全4度上に進む。Ⅴ→Ⅰ・Ⅱm→Ⅴ など）は、
//        完全4度上（+5）か、完全5度下（-7）の、どちらかだけ。どちらにするかは、全体の音域（低すぎ・高すぎ）で決まる
//      ・音域の帯（baseC-7 〜 baseC+11。C3 が標準なら F2〜B3）の外に出ると、1半音ごとに罰
//      ・終止（強進行で、フレーズの終わりの主和音 Ⅰ へ着く。ループのつなぎ目も）は、完全5度下を優先する
//        （4度上へ跳ぶと、罰が大きい）。フレーズの途中の主和音・Ⅵm 系への強進行（解決）も、やや優先する
//      ・ループのつなぎ目（最後 → 最初）も、費用に入れる。最後のコードが、最初のコードと同じルートなら、同じ高さになる
//      ・同じコードが続く（「→」も同じ）ときは、1つにまとめる（同じ高さ）
//      ・費用は、すべて整数。ゲーム（game/js/core/voicing.js）と、まったく同じ計算
//
//   ② 1つ前だけを見る簡易版（chooseOctaveShift）: 本来の高さと、その上下1オクターブのうち、前のコードのルートに一番近いものを選ぶ。
//      同じ近さなら、本来の高さ。試聴・ゲームとの照合に使う。
//
//   Arduino に依存しない（パソコンの上でもテストできる）。
// ============================================================

// ---- ② 1つ前だけを見る簡易版 ----
// 本来のルート（MIDIノート）から動かす量（-12 / 0 / +12 半音）を返す。
//   nominalRoot  : 本来の高さのルート（例: 48）
//   previousRoot : 前に鳴らしたコードの、実際のルート。まだ鳴らしていなければ -1
//   enabled      : false のときは、いつも 0（本来の高さ）
int chooseOctaveShift(int nominalRoot, int previousRoot, bool enabled);

// ---- ① 計画 ----
// 費用（整数）。game/js/core/voicing.js の PLAN と同じ値
enum {
  VOICE_PLAN_CAD1 = 20,   // 終止（強進行で、フレーズの終わり・つなぎ目の、主和音 Ⅰ へ着く）が、4度上へ跳ぶときの罰
  VOICE_PLAN_CAD2 = 8,    // 強進行で、フレーズの途中の主和音へ着く（解決）・Ⅵm 系へ着くときが、4度上へ跳ぶときの罰（Ⅵm 系は、ドミナントから着くときを、のぞく = 下の SEC）
  VOICE_PLAN_SEC = 8,     // セカンダリードミナントの動き（ドミナント・ツーファイブの Ⅱm7 → Ⅰ系以外への強進行）が、5度下へ動くときの罰（= 4度上を優先する。2026-11-25）
  VOICE_PLAN_PEN = 4,     // 音域の帯の外に出る、1半音ごとの罰
  VOICE_PLAN_BIG = 1000,  // 強進行なのに、4度上でも 5度下でもないときの罰
  VOICE_PLAN_OCT = 1,     // 本来の高さから、1オクターブずれるときの罰
  VOICE_PLAN_LOW = 7,     // 帯の下: baseC - 7
  VOICE_PLAN_HIGH = 11,   // 帯の上: baseC + 11
  VOICE_PLAN_MAX_NODES = 16
};

// 計画に使う、1つのコード（ループの順に並べる。休みは入れない）
struct VoicePlanNode {
  int8_t pc;     // ルートの音名の番号（C=0 ... B=11）。本来の高さ = baseC + pc
  int8_t goal;   // 着地先の強さ: 2 = 主和音 Ⅰ / 1 = Ⅵm 系（Ⅵm・Ⅵm7・Ⅵ）/ 0 = 着地先ではない
  bool final;    // フレーズの終わりか
  bool dom;      // ドミナントか: ドミナント7th・Ⅴ・Ⅵ の長三和音（セカンダリードミナントの、もとになる和音）
  bool ii;       // マイナー系か: Ⅱm・Ⅱm7・Ⅶm7♭5 など（ツーファイブの Ⅱ にあたる和音）
};

// nodes[0..n-1] の、本来の高さからのずれ（-12 / 0 / +12）を shifts[] に返す。nodes[0] は、いつも 0
void planOctaves(const VoicePlanNode* nodes, int n, int baseC, int8_t* shifts);

// 盤（位置ごとの駒のID。0 = 空き・未登録、99 = →）から、各ステップのルートのずれ（-12 / 0 / +12）を、まとめて決める。休みのステップは 0。
//   「→」は、前へたどって、最初に見つかった「→」でない駒のコード（先頭の「前」は最後の位置。grooveResolveChordId と同じ）
//   enabled が false のときは、全部 0（本来の高さ）
void planBoardShifts(const uint8_t* rawIds, int numSteps, const Key& key, int baseC, bool enabled, int8_t* shiftByStep);
