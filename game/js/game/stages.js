// ステージの定義（チュートリアル・フリープレイ・チャレンジ）。
//   チュートリアルは、「技」を1つずつ覚えるステージ。solution（お手本）から、「N番に〇〇を置こう」の案内を自動で作る。
//   ゲームの流れ（遊びの順番）は、ここを読めば分かる。文章は、音楽の用語を知らない人に向けて書いている。
//
//   id        : ステージの名前（保存にも使う。変えない）
//   goal      : クリアの条件。{ kind, variant? } = その技が盤の上で決まる / { kinds: [...] } = このどれかの技が決まる / { count: n } = 駒を n 個置く / { slots: [[位置, 駒], ...] } = 指定の駒を、指定の場所に置く
//               finish: [[位置, 駒], ...] を足すと、「技が決まって、かつ、その駒が、その場所に置かれている」とき（最後まで置かせる。例: 小室進行は、Ⅰ に着地するまで）
//   pieces    : 使える駒（駒の名前）。フリープレイは全部
//   instrument: （省略可）このステージの標準の音色の id（piano / epiano / guitar / organ / strings / drive / bell）。ユーザーが選んだ音色が、あれば、そちらが優先
//   drumId / backingId: このステージの標準のビート・バッキング（presets の番号）。同じく、ユーザーの選択が優先
//   noTricks  : true なら、技の判定をしない（最初のステージ。置いて聴くだけ）
//   solution  : お手本。[[位置(0〜7), 駒の名前], ...]。案内の矢印と、テストに使う
